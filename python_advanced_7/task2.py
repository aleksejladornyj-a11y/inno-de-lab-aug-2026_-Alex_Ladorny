# Фильтрация транзакций

raw_transactions = ["SUCCESS:100", "FAILED:50", "SUCCESS:-10", "SUCCESS:0", "SUCCESS:250", "ERROR:200"]

# Генератор списка:
# 1. Проходим по каждой транзакции (переменная t)
# 2. Проверяем, начинается ли строка с "SUCCESS:" (фильтруем только успешные)
# 3. Если да, извлекаем числовую часть после двоеточия и сразу преобразуем в int,
#    используя оператор моржа (:=), чтобы вычислить сумму один раз (избегаем повторного вычисления)
# 4. Проверяем, что сумма > 0 (отбрасываем нулевые и отрицательные платежи)
# 5. В список попадает только сумма (a), если все условия выполнены
filtered = [a for t in raw_transactions if t.startswith('SUCCESS:') and (a := int(t.split(':')[1])) > 0]

print('Очищенные транзакции:', filtered)